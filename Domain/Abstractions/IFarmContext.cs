namespace Domain.Abstractions;

/// <summary>
/// Ферма текущего пользователя. Определяет, данные какой фермы видны в рамках запроса
/// </summary>
public interface IFarmContext
{
    /// <summary>
    /// Уникальный идентификатор фермы текущего пользователя.
    /// Null означает отсутствие контекста фермы (вход в систему, миграции, инициализация) —
    /// в этом случае данные по фермам не фильтруются
    /// </summary>
    Guid? CurrentFarmId { get; }

    /// <summary>
    /// Устанавливает ферму текущего пользователя
    /// </summary>
    /// <param name="farmId">Уникальный идентификатор фермы или null, если пользователь не авторизован</param>
    void SetFarm(Guid? farmId);
}
